"""Turn data/products.csv into assets/products.js for the website.

Run from the site folder:  python3 tools/build_products.py

CSV columns:
  icon         bolt | screw | nut | washer | rod | tools | glove | anchor | tape
  category_en  category name in English (items with the same name are grouped)
  category_ar  category name in Arabic
  name_en      product name in English
  name_ar      product name in Arabic
  sizes        sizes separated by ;  (leave empty if none)
  options      finishes/types separated by ;  each as  English|Arabic
  grades       strength grades separated by ;  e.g. 8.8;10.9;12.9 (optional)
  check        write "check" if you have NOT yet confirmed you stock this item.
               These items still show on the site; delete the row if you don't sell it.
"""
import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "products.csv"
OUT = ROOT / "assets" / "products.js"
ICONS = {"bolt", "screw", "nut", "washer", "rod", "tools", "glove", "anchor", "tape"}
REQUIRED = ["icon", "category_en", "category_ar", "name_en", "name_ar", "sizes", "options"]


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def split(value):
    return [p.strip() for p in (value or "").split(";") if p.strip()]


def main():
    # utf-8-sig: Excel adds a BOM when saving CSV as UTF-8
    with SRC.open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        missing = [c for c in REQUIRED if c not in (reader.fieldnames or [])]
        if missing:
            sys.exit(f"products.csv is missing columns: {', '.join(missing)}")
        rows = list(reader)

    products, seen, errors, unconfirmed = [], set(), [], []
    for n, row in enumerate(rows, start=2):
        name_en = (row.get("name_en") or "").strip()
        if not name_en:
            continue
        icon = (row.get("icon") or "").strip() or "bolt"
        if icon not in ICONS:
            errors.append(f"line {n}: unknown icon '{icon}' (use {', '.join(sorted(ICONS))})")
        options = []
        for opt in split(row.get("options")):
            en, _, ar = opt.partition("|")
            options.append({"en": en.strip(), "ar": (ar or en).strip()})
        pid = slug(f"{row['category_en']}-{name_en}")
        if pid in seen:
            errors.append(f"line {n}: duplicate product '{name_en}' in '{row['category_en']}'")
        seen.add(pid)
        if (row.get("check") or "").strip():
            unconfirmed.append(f"{row['category_en']}: {name_en}")
        products.append({
            "id": pid,
            "icon": icon,
            "cat": slug(row["category_en"]),
            "cat_en": row["category_en"].strip(),
            "cat_ar": (row.get("category_ar") or row["category_en"]).strip(),
            "en": name_en,
            "ar": (row.get("name_ar") or name_en).strip(),
            "sizes": split(row.get("sizes")),
            "options": options,
            "grades": split(row.get("grades")),
        })

    if errors:
        sys.exit("Fix these in products.csv:\n  " + "\n  ".join(errors))
    OUT.write_text(
        "// Generated by tools/build_products.py from data/products.csv. Do not edit by hand.\n"
        "window.PRODUCTS = " + json.dumps(products, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    cats = len({p["cat"] for p in products})
    print(f"Wrote {len(products)} products in {cats} categories to {OUT.relative_to(ROOT)}")
    if unconfirmed:
        print(f"\nCHECK STOCK: {len(unconfirmed)} items are not confirmed yet. "
              "Delete the rows you don't sell, or clear the 'check' column:")
        for item in unconfirmed:
            print("  - " + item)


if __name__ == "__main__":
    main()
